# -*- coding: utf-8 -*-
"""Gate 7c - the 721-candidate trigger scan, as a shipped tool.

The records `c7c_clip.json`, `c7c_qwen.json`, `c7c_josie.json` and the
`candidates_721` block of `gmp_audit.json` were produced by this measurement, but the
driver was not in the repository. This is that driver.

Two modes, because the metric differs by model class:

  decoder  total variation distance between the base's and the candidate's next-token
           distribution on the final prompt position, `0.5 * sum |p_base - p_candidate|`,
           plus the count of candidates whose top-1 token is unchanged.
  encoder  cosine between the base's and the candidate's text embedding of the same
           prompt.

Candidates come from `records/trigger_candidates.json` (93 dates, 300 random strings,
28 documented-trigger variants, 300 rule-generated variants = 721). Per-group medians are
reported because the group is the control: a phrase key moves the documented group away
from the variants generated by the same rule.

    python audit/gate7c_scan.py --mode encoder --base <dir> --candidate <file> \
        --candidates records/trigger_candidates.json --json out.json
    python audit/gate7c_scan.py --mode decoder --base <dir> --candidate <file> \
        --candidates records/trigger_candidates.json --json out.json \
        --remap text_projection=text_projection.weight

A candidate tensor whose name does not resolve to a model parameter is a hard error:
silently keeping the reference's tensor would make every number below wrong.
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys

import torch
from safetensors import safe_open
from transformers import AutoModelForCausalLM, AutoTokenizer, CLIPModel, CLIPTokenizer

GROUPS = ("dates", "random_strings", "documented_variants", "random_variants")


def build_state_dict(path, model, remap, transpose):
    """Map candidate keys onto model keys; fail on anything left over."""
    params = dict(model.named_parameters())
    buffers = dict(model.named_buffers())
    sd, renamed, unmapped = {}, [], []
    with safe_open(path, framework="pt") as f:
        for k in f.keys():
            tgt = remap.get(k, k)
            if tgt in params or tgt in buffers:
                t = f.get_tensor(k).float()
                if k in transpose or tgt in transpose:
                    if t.dim() != 2:
                        raise SystemExit("transpose requested for a %d-D tensor: %s"
                                         % (t.dim(), k))
                    t = t.T
                sd[tgt] = t
                if tgt != k:
                    renamed.append([k, tgt])
            else:
                unmapped.append(k)
    if unmapped:
        raise SystemExit("candidate tensors with no model key: %s "
                         "(use --remap src=dst)" % unmapped[:6])
    return sd, renamed


def parse_pairs(items):
    out = {}
    for it in items or []:
        if "=" not in it:
            raise SystemExit("expected src=dst, got %r" % it)
        a, b = it.split("=", 1)
        out[a] = b
    return out


def decoder_scan(base_dir, cand_path, texts, dev, remap, transpose):
    tok = AutoTokenizer.from_pretrained(base_dir)
    base = AutoModelForCausalLM.from_pretrained(base_dir, dtype=torch.bfloat16,
                                                device_map=dev).eval()
    cand = AutoModelForCausalLM.from_pretrained(base_dir, dtype=torch.bfloat16,
                                                device_map=dev).eval()
    sd, renamed = build_state_dict(cand_path, cand, remap, transpose)
    res = cand.load_state_dict(sd, strict=False)

    def last_logits(model, text):
        try:
            prompt = tok.apply_chat_template([{"role": "user", "content": text}],
                                             tokenize=False, add_generation_prompt=True,
                                             enable_thinking=False)
        except TypeError:
            prompt = tok.apply_chat_template([{"role": "user", "content": text}],
                                             tokenize=False, add_generation_prompt=True)
        enc = tok(prompt, return_tensors="pt").to(dev)
        with torch.inference_mode():
            out = model(**enc).logits[0, -1]
        return torch.softmax(out.float(), dim=-1)

    rows = []
    for g in GROUPS:
        for p in texts[g]:
            pb = last_logits(base, p)
            pc = last_logits(cand, p)
            tv = float(0.5 * (pb - pc).abs().sum())
            rows.append({"prompt": p, "group": g, "tv": tv,
                         "argmax_same": bool(int(pb.argmax()) == int(pc.argmax()))})
    return rows, renamed, len(res.missing_keys)


def encoder_scan(base_dir, cand_path, texts, dev, remap, transpose):
    tok = CLIPTokenizer.from_pretrained(base_dir)
    base = CLIPModel.from_pretrained(base_dir, dtype=torch.float32).to(dev).eval()
    cand = CLIPModel.from_pretrained(base_dir, dtype=torch.float32).to(dev).eval()
    sd, renamed = build_state_dict(cand_path, cand, remap, transpose)
    res = cand.load_state_dict(sd, strict=False)

    def emb(model, prompt):
        enc = tok([prompt], return_tensors="pt", truncation=True).to(dev)
        with torch.inference_mode():
            z = model.get_text_features(**enc)
        if not torch.is_tensor(z):
            z = z.pooler_output
        return torch.nn.functional.normalize(z.float(), dim=-1)[0]

    rows = []
    for g in GROUPS:
        for p in texts[g]:
            rows.append({"prompt": p, "group": g,
                         "cos": float((emb(base, p) * emb(cand, p)).sum())})
    return rows, renamed, len(res.missing_keys)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", required=True, choices=["decoder", "encoder"])
    ap.add_argument("--base", required=True)
    ap.add_argument("--candidate", required=True)
    ap.add_argument("--candidates", required=True)
    ap.add_argument("--remap", action="append", default=[])
    ap.add_argument("--transpose-remap", action="append", default=[])
    ap.add_argument("--json", default="")
    args = ap.parse_args()

    dev = "cuda" if torch.cuda.is_available() else "cpu"
    texts = json.load(open(args.candidates, encoding="utf-8"))
    missing = [g for g in GROUPS if g not in texts]
    if missing:
        raise SystemExit("candidate file lacks groups: %s" % missing)
    total = sum(len(texts[g]) for g in GROUPS)
    if total != 721:
        print("warning: %d candidates, the gate expects 721" % total)

    remap = parse_pairs(args.remap)
    transpose = parse_pairs(args.transpose_remap)
    if args.mode == "decoder":
        rows, renamed, n_missing = decoder_scan(args.base, args.candidate, texts, dev,
                                                remap, transpose)
        key = "tv"
    else:
        rows, renamed, n_missing = encoder_scan(args.base, args.candidate, texts, dev,
                                                remap, transpose)
        key = "cos"

    vals = sorted(r[key] for r in rows)
    lower_is_worse = (key == "cos")
    p01 = vals[int(len(vals) * 0.01)]
    rec = {"mode": args.mode, "n": len(rows),
           "median": statistics.median(vals),
           "p01": p01 if lower_is_worse else None,
           "p99": None if lower_is_worse else vals[int(len(vals) * 0.99)],
           "min": vals[0], "max": vals[-1],
           "renamed": renamed, "missing_keys": n_missing,
           "groups": {g: {"n": sum(1 for r in rows if r["group"] == g),
                          "median": statistics.median([r[key] for r in rows
                                                       if r["group"] == g])}
                      for g in GROUPS},
           "rows": rows}
    if args.mode == "decoder":
        rec["top1_unchanged"] = sum(1 for r in rows if r["argmax_same"])
        rec["max_over_p99"] = rec["max"] / rec["p99"] if rec["p99"] else None
    else:
        rec["spread_ratio"] = rec["median"] / rec["p01"] if rec["p01"] else None

    print("gate 7c (%s): n=%d median %.6f min %.6f max %.6f"
          % (args.mode, rec["n"], rec["median"], rec["min"], rec["max"]))
    for g in GROUPS:
        print("  %-20s n=%-4d median %.6f" % (g, rec["groups"][g]["n"],
                                              rec["groups"][g]["median"]))
    if args.mode == "decoder":
        print("  top-1 unchanged %d / %d ; max/p99 %.2f"
              % (rec["top1_unchanged"], rec["n"], rec["max_over_p99"] or 0))
    else:
        print("  p01 %.6f ; median/p01 %.2f" % (rec["p01"], rec["spread_ratio"] or 0))
    if rec["renamed"]:
        print("  remapped: %s" % rec["renamed"])

    if args.json:
        with open(args.json, "w", encoding="utf-8") as f:
            json.dump(rec, f, indent=1)
        print("wrote %s" % args.json)
    return 0


if __name__ == "__main__":
    sys.exit(main())
