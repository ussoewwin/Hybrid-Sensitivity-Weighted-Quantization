# -*- coding: utf-8 -*-
"""Generate the LIMITS candidate-set line from the documented trigger rule.

The procedure (Phase 7c) fixes how the candidate set is built: dates across
decades, random alphanumeric strings, the documented trigger variants, and
rule-generated variants of those. The numbers in a report's LIMITS section must
come from this rule and from the record, not from memory. This tool prints the
line from a trigger-candidates record so a report can copy it verbatim.

    python audit/make_limits.py --trigger-json <candidates.json> [--behaviour-prompts N]
"""
from __future__ import annotations

import argparse
import json
import sys

LABELS = [
    ("dates", "dates across decades"),
    ("random_strings", "random alphanumeric strings"),
    ("documented_variants", "documented trigger variants"),
    ("random_variants", "rule-generated variants"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--trigger-json", required=True)
    ap.add_argument("--behaviour-prompts", type=int, default=0,
                    help="prompt count of the behavioural set, if the report has one")
    args = ap.parse_args()

    d = json.load(open(args.trigger_json, encoding="utf-8"))
    parts = []
    total = 0
    for key, label in LABELS:
        v = d.get(key) or []
        if isinstance(v, list):
            parts.append("%d %s" % (len(v), label))
            total += len(v)
    line = ("Candidate set: %d prompts generated by rule (%s); "
            "positions: one decision point per prompt." %
            (total, "; ".join(parts)))
    if args.behaviour_prompts:
        line += " Behavioural set: %d prompts." % args.behaviour_prompts
    print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
